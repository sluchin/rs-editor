#!/usr/bin/env python3
"""docstring を集めて po/rseditor.pot を作り, 各言語の PO (po/*.po) に混ぜる (gettext の xgettext と msgmerge に当たる).

使い方: update.py [--check]

- lisp/*.scm の `define` と `define-command` の docstring を集める
  (関数は, 引数の後の文字列 (本体が文字列だけなら, docstring でない). 変数は, `(define name value "doc")` の 3 つ目)。
- msgctxt は `function:名前` か `variable:名前`, msgid は docstring (英語)。
- 各言語の PO は, 同じ msgctxt の翻訳を残す。docstring が変わった翻訳は, `#, fuzzy` の印を付け,
  元の docstring を `#| msgid` に残す (エディタは, fuzzy の翻訳を出さない)。無くなった docstring の翻訳は, 消す。
- --check: ファイルを書かず, 作り直す要るものがあれば, 1 で終わる (lint 用)。
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
POT = ROOT / 'po' / 'rseditor.pot'
HEADER_COMMENT = [
    '# Docstrings of rs-editor. Generated by tools/po/update.py; do not edit.',
    '# msgctxt is "function:NAME" or "variable:NAME"; msgid is the English docstring.',
]


# --- Scheme の読み込み (docstring を取り出すのに, 足りるだけ) ---

TOKEN = re.compile(r'''
    (?P<space>\s+|;[^\n]*)
  | (?P<string>"(?:[^"\\]|\\.)*")
  | (?P<open>[(\[])
  | (?P<close>[)\]])
  | (?P<quote>['`]|,@|,)
  | (?P<char>\#\\(?:[a-zA-Z]+|.))
  | (?P<atom>[^\s()\[\]";'`,]+)
''', re.X | re.S)

ESCAPES = {'n': '\n', 't': '\t', '"': '"', '\\': '\\'}


class Str(str):
    """Scheme の文字列 (記号と区別する)."""


def unescape(text):
    """Scheme の文字列の中身 (\\n などを戻す)."""
    return Str(re.sub(r'\\(.)', lambda m: ESCAPES.get(m.group(1), m.group(1)), text[1:-1], flags=re.S))


class Quote(str):
    """式の前の ' などの印 (次の式と, 1 つの式にする)."""


def read_all(code):
    """ファイルの全ての式 (リストは Python のリスト, 文字列は Str, ほかは str. 'x は ['quote', x])."""
    stack = [[]]

    def push(item):
        # 前が ' などの印なら, 印と合わせて 1 つの式にする
        while stack[-1] and isinstance(stack[-1][-1], Quote):
            item = [str(stack[-1].pop()), item]
        stack[-1].append(item)

    for m in TOKEN.finditer(code):
        kind = m.lastgroup
        if kind == 'space':
            continue
        if kind == 'open':
            stack.append([])
        elif kind == 'close':
            push(stack.pop())
        elif kind == 'string':
            push(unescape(m.group()))
        elif kind == 'quote':
            stack[-1].append(Quote(m.group()))
        else:
            push(m.group())
    return stack[0]


def docstrings(path):
    """ファイルの docstring の [(msgctxt, msgid)] (定義した順)."""
    found = []
    for form in read_all(path.read_text()):
        if not (isinstance(form, list) and form and form[0] in ('define', 'define-command')):
            continue
        target = form[1] if len(form) > 1 else None
        if isinstance(target, list) and target and not isinstance(target[0], Str):
            body = form[2:]
            if len(body) > 1 and isinstance(body[0], Str):
                found.append((f'function:{target[0]}', str(body[0])))
        elif isinstance(target, str) and not isinstance(target, Str):
            if len(form) == 4 and isinstance(form[3], Str):
                found.append((f'variable:{target}', str(form[3])))
    return found


# --- PO の読み書き ---

def po_string(text):
    """PO の文字列 (複数行なら, 1 行目を空にして, 行ごとに分ける)."""
    def quote(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t').replace('\n', '\\n') + '"'
    if '\n' not in text:
        return quote(text)
    lines = text.split('\n')
    parts = [line + '\n' for line in lines[:-1]] + ([lines[-1]] if lines[-1] else [])
    return '""\n' + '\n'.join(quote(p) for p in parts)


def po_unquote(lines):
    """PO の文字列の行 ("..." の並び) をつなげて, 中身にする."""
    text = ''.join(re.fullmatch(r'\s*"(.*)"\s*', line, re.S).group(1) for line in lines)
    return re.sub(r'\\(.)', lambda m: ESCAPES.get(m.group(1), m.group(1)), text)


def parse_po(text):
    """PO の項目の [{'comments', 'flags', 'ctxt', 'id', 'str'}] (始めのヘッダも入れる. 古い項目 (#~) は除く)."""
    entries = []
    for block in re.split(r'\n\s*\n', text.strip()):
        entry = {'comments': [], 'flags': set(), 'ctxt': None, 'id': None, 'str': None}
        key, values, previous = None, [], []

        def finish():
            if key:
                entry[key] = po_unquote(values)

        for line in block.split('\n'):
            if line.startswith('#~'):
                continue
            if line.startswith('#,'):
                entry['flags'] |= {f.strip() for f in line[2:].split(',')}
            elif line.startswith('#|'):
                # fuzzy の翻訳の, 前の msgid
                previous.append(re.sub(r'^#\|\s*(msgid\s+)?', '', line))
            elif line.startswith('#'):
                entry['comments'].append(line)
            elif m := re.match(r'(msgctxt|msgid|msgstr)\s+(".*")$', line):
                finish()
                key = {'msgctxt': 'ctxt', 'msgid': 'id', 'msgstr': 'str'}[m.group(1)]
                values = [m.group(2)]
            elif line.startswith('"'):
                values.append(line)
        finish()
        if previous:
            entry['previous'] = po_unquote(previous)
        if entry['id'] is not None:
            entries.append(entry)
    return entries


def render(entries, header_comment):
    """PO の文 (ヘッダと, 項目)."""
    out = list(header_comment)
    for e in entries:
        out += e.get('comments', [])
        if e.get('flags'):
            out.append('#, ' + ', '.join(sorted(e['flags'])))
        if e.get('previous') is not None:
            out += ['#| msgid ' + line for line in po_string(e['previous']).split('\n')[:1]]
            out += ['#| ' + line for line in po_string(e['previous']).split('\n')[1:]]
        if e['ctxt'] is not None:
            out.append('msgctxt ' + po_string(e['ctxt']))
        out.append('msgid ' + po_string(e['id']))
        out.append('msgstr ' + po_string(e['str']))
        out.append('')
    return '\n'.join(out)


def pot_entries():
    """全ての docstring の, POT の項目 (ファイルの順, 定義した順)."""
    entries = []
    for path in sorted((ROOT / 'lisp').glob('*.scm')):
        for ctxt, msgid in docstrings(path):
            entries.append({'comments': [f'#: {path.relative_to(ROOT)}'], 'flags': set(),
                            'ctxt': ctxt, 'id': msgid, 'str': ''})
    return entries


def merge(po_text, template):
    """PO の翻訳を, POT の項目に混ぜる (msgmerge に当たる)."""
    old = parse_po(po_text)
    header = old[0] if old and old[0]['id'] == '' else {'comments': [], 'flags': set(), 'ctxt': None, 'id': '', 'str': ''}
    by_ctxt = {e['ctxt']: e for e in old if e['ctxt'] is not None}
    merged = [{**header, 'comments': [c for c in header['comments'] if not c.startswith('#:')]}]
    for t in template:
        e = {**t}
        previous = by_ctxt.get(t['ctxt'])
        if previous and previous['str']:
            e['str'] = previous['str']
            if previous['id'] != t['id']:
                # 元の docstring が変わった. 古い翻訳を残し, fuzzy の印を付ける
                e['flags'] = {'fuzzy'}
                e['previous'] = previous['id']
            elif 'fuzzy' in previous['flags']:
                e['flags'] = {'fuzzy'}
                e['previous'] = previous.get('previous')
        merged.append(e)
    return merged


def main():
    check = '--check' in sys.argv[1:]
    template = pot_entries()
    pot_header = {'comments': [], 'flags': set(), 'ctxt': None, 'id': '',
                  'str': 'Content-Type: text/plain; charset=UTF-8\n'}
    outputs = {POT: render([pot_header] + template, HEADER_COMMENT)}
    for po in sorted((ROOT / 'po').glob('*.po')):
        # ファイルの始めの説明 (# の行) は, ヘッダの項目のコメントとして残る
        outputs[po] = render(merge(po.read_text(), template), [])
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    for path in stale:
        if check:
            print(f'{path.relative_to(ROOT)}: out of date (run tools/po/update.py)')
        else:
            path.write_text(outputs[path])
            print(f'{path.relative_to(ROOT)}: updated')
    for po in sorted((ROOT / 'po').glob('*.po')):
        entries = parse_po(outputs[po])[1:]
        untranslated = sum(1 for e in entries if not e['str'])
        fuzzy = sum(1 for e in entries if 'fuzzy' in e['flags'])
        print(f'{po.relative_to(ROOT)}: {len(entries) - untranslated - fuzzy} translated, '
              f'{fuzzy} fuzzy, {untranslated} untranslated')
    return 1 if check and stale else 0


if __name__ == '__main__':
    sys.exit(main())

//! フォームの字下げの指定 (Emacs 30 の `emacs -Q` の, シンボルの `lisp-indent-function` と `scheme-indent-function`).
//!
//! 作り方: `emacs -Q --batch` で, `mapatoms` から, `function-get` (Emacs Lisp) と `get` (Scheme) の値を集める.
//! 名前順に並べてあるので, 二分探索で引く.

/// 字下げの指定.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Spec {
    /// 特別な引数の数.
    Args(usize),
    /// 定義の形.
    Defun,
    /// 名前付きの let を見分ける (Emacs の `scheme-let-indent`).
    Let,
}

/// 名前の指定を引きます.
pub fn lookup(table: &[(&str, Spec)], name: &str) -> Option<Spec> {
    table
        .binary_search_by(|(n, _)| (*n).cmp(name))
        .ok()
        .map(|i| table[i].1)
}

